#!/usr/bin/env python3
"""Generate C struct definitions with computed padding and offset asserts from a layout spec.

Usage: tools/structs/gen_struct.py SPEC OUT.h GUARD [#include ...]

Spec: `@Name 0xSIZE` starts a struct; each following line is `0xOFF type name [comment]`
(`void_ptr` for `void *`, `name[N]` for arrays). Fields may be added in any order of discovery:
unknown gaps become `padXXX` arrays, so parallel edits to different fields merge cleanly.
"""
import sys

SIZES = {
    "uint8_t": 1, "int8_t": 1, "uint16_t": 2, "int16_t": 2, "uint32_t": 4, "int32_t": 4, "float": 4,
    "void *": 4, "ZVec3": 12, "ZMatrix": 64, "ZAngle3": 6, "PhysContactSnap": 0x1fc,
    "PhysWheel": 0x84, "ZAngle": 2, "double": 8, "int8_t ": 1,
}


def parse(spec):
    fields = []
    for line in spec.strip().splitlines():
        line = line.split("#")[0].strip()
        if not line:
            continue
        parts = line.split(None, 3)
        off = int(parts[0], 16)
        ty = parts[1].replace("_", " ") if parts[1] == "void_ptr" else parts[1]
        if parts[1] == "void_ptr":
            ty = "void *"
        name = parts[2]
        cmt = parts[3] if len(parts) > 3 else ""
        cmt = cmt.replace("/*", "").replace("*/", "").strip()
        fields.append((off, ty, name, cmt))
    return fields


def emit(tag, fields, size, idx_note=""):
    out = []
    cur = 0
    pads = 0
    asserts = []
    for off, ty, name, cmt in fields:
        assert off >= cur, f"{name}: offset {off:#x} overlaps (cur {cur:#x})"
        if off > cur:
            gap = off - cur
            out.append(f"    uint8_t pad{cur:03x}[{gap:#x}];")
            cur = off
        arr = ""
        base = ty
        if "[" in name:
            nm, cnt = name.split("[")
            cnt = cnt.rstrip("]")
            arr = f"[{cnt}]"
            sz = SIZES[base] * int(cnt, 0)
            cname = nm
        else:
            sz = SIZES[base]
            cname = name
        decl = f"    {ty}{'' if ty.endswith('*') else ' '}{name};"
        if cmt:
            decl += f" /* {cmt} */"
        out.append(decl)
        asserts.append((cname, off))
        cur += sz
    if cur < size:
        out.append(f"    uint8_t pad{cur:03x}[{size - cur:#x}];")
    assert cur <= size, f"{tag}: fields extend to {cur:#x} > {size:#x}"
    return out, asserts


def main():
    spec = open(sys.argv[1]).read()
    sections = {}
    key = None
    for line in spec.splitlines():
        if line.startswith("@"):
            key = line[1:].split()
            sections[key[0]] = (int(key[1], 0), [])
        elif key:
            sections[key[0]][1].append(line)
    out, guard = sys.argv[2], sys.argv[3]
    lines = [f"/* Generated by tools/structs/gen_struct.py from {sys.argv[1]}; edit the spec, not this file. */",
             f"#ifndef {guard}", f"#define {guard}", "", "#include <stddef.h>", "#include <stdint.h>", ""]
    lines += [f"#include {inc}" for inc in sys.argv[4:]] + [""]
    for tag, (size, body_lines) in sections.items():
        fields = parse("\n".join(body_lines))
        SIZES[tag] = size
        body, asserts = emit(tag, fields, size)
        lines += [f"typedef struct {tag} {{", *body, f"}} {tag};", ""]
        lines.append(f'_Static_assert(sizeof({tag}) == {size:#x}, "{tag} size");')
        lines += [f'_Static_assert(offsetof({tag}, {n}) == {o:#x}, "{tag}.{n}");' for n, o in asserts]
        lines.append("")
    lines += [f"#endif", ""]
    open(out, "w").write("\n".join(lines))


main()
