#!/usr/bin/env python3
"""Writes the music edit list (data/music-edits.json, docs/MUSIC.md) as a C table for the music override
(src/platform/music.h: bmxMusicEdits). Usage: gen_music_edits.py <music-edits.json> <out.c>"""
import json
import sys


def c_string(text):
    """A C string literal; every byte outside printable ASCII as a 3-digit octal escape (UTF-8)."""
    out = []
    for byte in text.encode("utf-8"):
        ch = chr(byte)
        if ch in '"\\':
            out.append("\\" + ch)
        elif 0x20 <= byte < 0x7F:
            out.append(ch)
        else:
            out.append("\\%03o" % byte)
    return '"' + "".join(out) + '"'


def confidence(text):
    for name, value in (("high", "kBmxMusicHigh"), ("medium", "kBmxMusicMedium"), ("low", "kBmxMusicLow")):
        if text.startswith(name):
            return value
    raise SystemExit("unknown confidence %r" % text)


def level(segment):
    """The level ratio game / CD of a segment. The edit list's gain is a least-squares fit, which is the level
    ratio times the correlation: divide it out (Cypress Hill, correlated at ~0.8, would play 2 dB quiet)."""
    return segment["gain"] / segment["corr"]


def track_level(track):
    """The track's level, as data/music-edits.json's gain_linear is computed (duration-weighted over the
    segments correlated above 0.97, else the median) but from the level ratios."""
    segs = [s for s in track["segments"] if s["corr"] > 0.97]
    if segs:
        weights = [s["game_end"] - s["game_start"] for s in segs]
        return sum(w * level(s) for w, s in zip(weights, segs)) / sum(weights)
    values = sorted(level(s) for s in track["segments"])
    return values[len(values) // 2]


def main():
    src, dst = sys.argv[1], sys.argv[2]
    with open(src, encoding="utf-8") as f:
        tracks = json.load(f)
    lines = [
        "/* Generated by tools/gen_music_edits.py from data/music-edits.json: do not edit. */",
        '#include "platform/music.h"',
        "",
    ]
    for t in tracks:
        lines.append("static const BmxMusicSegment kSegments%d[] = {" % t["track_index"])
        for s in t["segments"]:
            lines.append(
                "    {%d, %d, %d, %d, %.4ff, %s},"
                % (s["game_start"], s["game_end"], s["flac_start"], s["flac_end"], level(s),
                   confidence(s["confidence"]))
            )
        lines.append("};")
    lines.append("")
    lines.append("const BmxMusicEdit bmxMusicEdits[] = {")
    for t in sorted(tracks, key=lambda t: t["track_index"]):
        assert t["sample_rate"] == 44100
        fade = t["fade_out"] or {"start_game": 0, "end_game": 0, "final_ratio": 1.0}
        lines.append(
            "    {%d, %s, %s, %d, %d, %.4ff, %d, %d, %.4ff, kSegments%d, %d},"
            % (t["track_index"], c_string(t["title"]), c_string(t["flac_file"]), t["flac_samples"],
               t["game_samples"], track_level(t), fade["start_game"], fade["end_game"], fade["final_ratio"],
               t["track_index"], len(t["segments"]))
        )
    lines.append("};")
    lines.append("const uint32_t bmxMusicEditCount = %d;" % len(tracks))
    with open(dst, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
